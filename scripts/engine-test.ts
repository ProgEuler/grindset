import { createState, runKeys, type Pos } from "../src/lib/vim/engine"

let fail = 0
function check(name: string, text: string, cursor: Pos, keys: string, wantText: string, wantCursor?: Pos) {
  const ks = (keys.match(/<[^>]+>|./g) ?? []).map((k) => (k === "<CR>" ? "Enter" : k === "<BS>" ? "Backspace" : k))
  const st = runKeys(createState(text, cursor), ks)
  const got = st.lines.join("\n")
  const okText = got === wantText
  const okCur = !wantCursor || (st.cursor.line === wantCursor.line && st.cursor.col === wantCursor.col)
  if (!okText || !okCur) {
    fail++
    console.log(`FAIL ${name}\n  got:  ${JSON.stringify(got)} @${JSON.stringify(st.cursor)} mode=${st.mode}\n  want: ${JSON.stringify(wantText)} @${JSON.stringify(wantCursor)}`)
  }
}
